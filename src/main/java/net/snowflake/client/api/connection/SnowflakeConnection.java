package net.snowflake.client.api.connection;

import java.io.InputStream;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLFeatureNotSupportedException;
import net.snowflake.client.api.resultset.QueryStatus;

/** This interface defines Snowflake specific APIs for Connection */
public interface SnowflakeConnection {
  /**
   * Upload data from a stream to a Snowflake stage with required parameters only.
   *
   * <p>This is a convenience method that uses default options (compress data, no destination
   * prefix). For advanced configuration, use {@link #uploadStream(String, String, InputStream,
   * UploadStreamConfig)}.
   *
   * <p>The caller is responsible for closing the input stream after upload completes.
   *
   * @param stageName the name of the stage (e.g., "@my_stage")
   * @param destFileName the destination file name on the stage
   * @param inputStream the input stream containing data to upload
   * @throws SQLException if upload fails
   */
  void uploadStream(String stageName, String destFileName, InputStream inputStream)
      throws SQLException;

  /**
   * Upload data from a stream to a Snowflake stage with optional configuration.
   *
   * <p>This method allows customization of upload behavior via {@link UploadStreamConfig}, such as
   * setting a destination prefix or controlling compression.
   *
   * <p>The caller is responsible for closing the input stream after upload completes.
   *
   * @param stageName the name of the stage (e.g., "@my_stage")
   * @param destFileName the destination file name on the stage
   * @param inputStream the input stream containing data to upload
   * @param config optional configuration for upload behavior
   * @throws SQLException if upload fails
   */
  void uploadStream(
      String stageName, String destFileName, InputStream inputStream, UploadStreamConfig config)
      throws SQLException;

  /**
   * Download a file from a Snowflake stage as a stream with required parameters only.
   *
   * <p>This is a convenience method that uses default options (no decompression). For advanced
   * configuration, use {@link #downloadStream(String, String, DownloadStreamConfig)}.
   *
   * <p>The caller is responsible for closing the returned input stream.
   *
   * @param stageName the name of the stage (e.g., "@my_stage")
   * @param sourceFileName the path to the file within the stage
   * @return an input stream containing the file data
   * @throws SQLException if download fails
   */
  InputStream downloadStream(String stageName, String sourceFileName) throws SQLException;

  /**
   * Download a file from a Snowflake stage as a stream with optional configuration.
   *
   * <p>This method allows customization of download behavior via {@link DownloadStreamConfig}, such
   * as automatic decompression.
   *
   * <p>The caller is responsible for closing the returned input stream.
   *
   * @param stageName the name of the stage (e.g., "@my_stage")
   * @param sourceFileName the path to the file within the stage
   * @param config optional configuration for download behavior
   * @return an input stream containing the file data
   * @throws SQLException if download fails
   */
  InputStream downloadStream(String stageName, String sourceFileName, DownloadStreamConfig config)
      throws SQLException;

  /**
   * Return unique session ID from current session generated by making connection
   *
   * @return a unique alphanumeric value representing current session ID
   * @throws SQLException if an error occurs
   */
  String getSessionID() throws SQLException;

  /**
   * Return the status of a query.
   *
   * @param queryID the query ID.
   * @return the status of the query.
   * @throws SQLException if an error occurs.
   */
  QueryStatus getQueryStatus(String queryID) throws SQLException;

  /**
   * Create a new instance of a ResultSet object based off query ID. ResultSet will contain results
   * of corresponding query. Used when original ResultSet object is no longer available, such as
   * when original connection has been closed.
   *
   * @param queryID the query ID
   * @return ResultSet based off the query ID
   * @throws SQLException if an error occurs
   */
  ResultSet createResultSet(String queryID) throws SQLException;

  /**
   * Return an array of child query IDs for the given query ID.
   *
   * <p>If the given query ID is for a multiple statements query, it returns an array of its child
   * statements, otherwise, it returns an array to include the given query ID.
   *
   * @param queryID The given query ID
   * @return An array of child query IDs
   * @throws SQLException If the query is running or the corresponding query is FAILED.
   */
  String[] getChildQueryIds(String queryID) throws SQLException;

  /**
   * Get the major version of the Snowflake database.
   *
   * @return database major version
   * @throws SQLException if an error occurs
   */
  int getDatabaseMajorVersion() throws SQLException;

  /**
   * Get the minor version of the Snowflake database.
   *
   * @return database minor version
   * @throws SQLException if an error occurs
   */
  int getDatabaseMinorVersion() throws SQLException;

  /**
   * Get the full version string of the Snowflake database.
   *
   * @return database version string
   * @throws SQLException if an error occurs
   */
  String getDatabaseVersion() throws SQLException;

  /**
   * Get the current role for the session.
   *
   * @return the current role name, or null if no role is set
   * @throws SQLException if the connection is closed or an error occurs
   */
  String getRole() throws SQLException;

  /**
   * Get the current warehouse for the session.
   *
   * @return the current warehouse name, or null if no warehouse is set
   * @throws SQLException if the connection is closed or an error occurs
   */
  String getWarehouse() throws SQLException;

  /**
   * Get the current database for the session.
   *
   * <p>This is equivalent to {@link java.sql.Connection#getCatalog()} but uses Snowflake-specific
   * terminology for discoverability.
   *
   * @return the current database name, or null if no database is set
   * @throws SQLException if the connection is closed or an error occurs
   */
  String getDatabase() throws SQLException;

  /**
   * Return the value of a Snowflake session parameter as a {@link String}.
   *
   * <p>Session parameters are the key-value pairs the server returns at login and refreshes with
   * query responses (e.g. {@code QUERY_TAG}, {@code TIMEZONE}, {@code AUTOCOMMIT}). The lookup
   * reflects the most recent parameter block and matches the name case-insensitively.
   *
   * <p>Values are converted with {@link Object#toString()}, so a boolean parameter returns {@code
   * "true"} or {@code "false"} and a numeric parameter returns its decimal form.
   *
   * <p><b>Default implementation:</b> rejects a {@code null} name, then throws {@link
   * SQLFeatureNotSupportedException} so that third-party or mock implementors that have not yet
   * added this capability fail explicitly rather than silently returning {@code null}.
   * Implementations backed by a live Snowflake session must override this method.
   *
   * @param parameterName the session parameter name; case-insensitive, must not be {@code null}
   * @return the parameter value as a {@link String} (booleans and numbers in their {@code
   *     toString()} form), or {@code null} if the current session state does not contain the
   *     parameter
   * @throws SQLFeatureNotSupportedException if called on an implementation that has not overridden
   *     this method
   * @throws SQLException if the connection is closed; this check comes before argument validation
   * @throws IllegalArgumentException if {@code parameterName} is {@code null}
   * @since 4.4.1
   */
  default String getSessionParameter(String parameterName) throws SQLException {
    if (parameterName == null) {
      throw new IllegalArgumentException("parameterName must not be null");
    }
    throw new SQLFeatureNotSupportedException(
        "getSessionParameter is not supported by this SnowflakeConnection implementation."
            + " Override this method to provide session-parameter access.");
  }

  /**
   * Submit a JSON-encoded telemetry event to the Snowflake in-band telemetry service.
   *
   * <p>This is a <em>best-effort, fire-and-forget</em> call:
   *
   * <ul>
   *   <li>Each call results in its own asynchronous HTTP request. The event is queued in a
   *       dedicated application-telemetry batch that is <em>separate</em> from the JDBC driver's
   *       own diagnostic batch, so a server rejection of an application payload cannot disable
   *       driver-internal telemetry.
   *   <li>The driver injects (or overwrites) a {@code "source"} key into the submitted object so
   *       server-side consumers can distinguish application events from driver events. Do not rely
   *       on round-tripping the value of that key.
   *   <li>Payloads longer than 64 KiB (measured in UTF-16 code units) are silently discarded.
   *   <li>If in-band telemetry is disabled for the session, the event is dropped without an error.
   *   <li>Send failures are handled on the telemetry thread and are not reported to the caller.
   *   <li>{@code jsonPayload} must be a JSON object. Payloads that are not valid JSON, or are a
   *       JSON array or scalar, are discarded.
   * </ul>
   *
   * <p><b>Default implementation:</b> rejects a {@code null} payload, then throws {@link
   * SQLFeatureNotSupportedException} so that third-party or mock implementors that have not yet
   * added telemetry support fail explicitly rather than silently dropping events. Implementations
   * backed by a live Snowflake session must override this method.
   *
   * @param jsonPayload a JSON object string to submit as the telemetry payload; must not be {@code
   *     null}
   * @throws SQLFeatureNotSupportedException if called on an implementation that has not overridden
   *     this method
   * @throws SQLException if the connection is closed; this check comes before argument validation
   * @throws IllegalArgumentException if {@code jsonPayload} is {@code null}
   * @since 4.4.1
   */
  default void submitTelemetry(String jsonPayload) throws SQLException {
    if (jsonPayload == null) {
      throw new IllegalArgumentException("jsonPayload must not be null");
    }
    throw new SQLFeatureNotSupportedException(
        "submitTelemetry is not supported by this SnowflakeConnection implementation."
            + " Override this method to submit telemetry through the session telemetry client.");
  }
}
